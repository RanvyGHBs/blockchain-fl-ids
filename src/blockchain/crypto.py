"""
Cryptographic Identity and Digital Signature Engine.
Uses ECDSA (Elliptic Curve Digital Signature Algorithm with SECP256R1)
to sign model update hashes and guarantee non-repudiation across federated participants.
"""

import base64
import hashlib
from typing import Tuple
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.serialization import (
    Encoding, PublicFormat, PrivateFormat, NoEncryption,
    load_pem_private_key, load_pem_public_key
)


class CryptoManager:
    """
    Manages asymmetric keypair generation, digital signing, and signature verification.
    """

    @staticmethod
    def generate_keypair() -> Tuple[str, str]:
        """
        Generates an ECDSA SECP256R1 keypair.
        Returns:
            (private_key_pem_str, public_key_pem_str)
        """
        private_key = ec.generate_private_key(ec.SECP256R1())
        public_key = private_key.public_key()

        priv_pem = private_key.private_bytes(
            encoding=Encoding.PEM,
            format=PrivateFormat.PKCS8,
            encryption_algorithm=NoEncryption()
        ).decode("utf-8")

        pub_pem = public_key.public_bytes(
            encoding=Encoding.PEM,
            format=PublicFormat.SubjectPublicKeyInfo
        ).decode("utf-8")

        return priv_pem, pub_pem

    @staticmethod
    def sign_message(private_key_pem: str, message: str) -> str:
        """
        Signs a message string (or hash) using the client's private key.
        Returns base64-encoded signature.
        """
        priv_key = load_pem_private_key(private_key_pem.encode("utf-8"), password=None)
        signature = priv_key.sign(
            message.encode("utf-8"),
            ec.ECDSA(hashes.SHA256())
        )
        return base64.b64encode(signature).decode("utf-8")

    @staticmethod
    def verify_signature(public_key_pem: str, message: str, signature_b64: str) -> bool:
        """
        Verifies whether a digital signature was generated by the corresponding private key.
        Guarantees non-repudiation of submitted model updates.
        """
        try:
            pub_key = load_pem_public_key(public_key_pem.encode("utf-8"))
            signature = base64.b64decode(signature_b64.encode("utf-8"))
            pub_key.verify(
                signature,
                message.encode("utf-8"),
                ec.ECDSA(hashes.SHA256())
            )
            return True
        except Exception:
            return False

    @staticmethod
    def sha256_hash(data: str) -> str:
        """Computes standard SHA-256 hexadecimal digest."""
        return hashlib.sha256(data.encode("utf-8")).hexdigest()
